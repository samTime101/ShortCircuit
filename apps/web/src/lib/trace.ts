import type { CircuitIR, SimulationSnapshot } from "@shortcircuit/engine";

/**
 * A recorded run of the simulator.
 *
 * Every input change, clock step, or forced state adds one sample, so the
 * waveform panel can show how a sequential circuit behaved over time.
 */

export interface TraceEvent {
  edge: "rising" | "falling";
  clock: string;
}

export interface TraceSample {
  /** What caused the sample, for example "clock" or "step". */
  label: string;
  inputs: Record<string, string>;
  outputs: Record<string, string>;
  states: Record<string, string>;
  events: TraceEvent[];
}

/** The maximum number of samples kept in memory. */
export const TRACE_LIMIT = 10_000;

export function sampleFromSnapshot(
  snapshot: SimulationSnapshot,
  label: string,
): TraceSample {
  return {
    label,
    inputs: mapValues(snapshot.inputs),
    outputs: mapValues(snapshot.outputs),
    states: mapValues(snapshot.states),
    events: snapshot.firedEvents.map((event) => ({
      edge: event.edge,
      clock: event.clock,
    })),
  };
}

function mapValues(signals: Record<string, { binary: string }>): Record<string, string> {
  const result: Record<string, string> = {};
  for (const [name, signal] of Object.entries(signals)) result[name] = signal.binary;
  return result;
}

/** Appends a sample, dropping the oldest one when the cap is reached. */
export function appendSample(trace: TraceSample[], sample: TraceSample): TraceSample[] {
  const next = [...trace, sample];
  return next.length > TRACE_LIMIT ? next.slice(next.length - TRACE_LIMIT) : next;
}

/** The signal rows of the waveform, in a stable order. */
export function traceSignals(circuit: CircuitIR): Array<{
  name: string;
  width: number;
  group: "input" | "output" | "state";
}> {
  return [
    ...circuit.inputs.map((input) => ({ name: input.name, width: input.width, group: "input" as const })),
    ...circuit.outputs.map((output) => ({ name: output.name, width: output.width, group: "output" as const })),
    ...circuit.states.map((state) => ({ name: state.name, width: state.width, group: "state" as const })),
  ];
}

export function valueFor(
  sample: TraceSample,
  group: "input" | "output" | "state",
  name: string,
): string {
  if (group === "input") return sample.inputs[name] ?? "0";
  if (group === "output") return sample.outputs[name] ?? "0";
  return sample.states[name] ?? "0";
}

function vcdIdentifier(index: number): string {
  // Printable ASCII, starting at '!', the way most tools do it.
  const code = 33 + index;
  return String.fromCharCode(code);
}

/** Writes the trace as a Value Change Dump that GTKWave and friends read. */
export function traceToVcd(circuit: CircuitIR, trace: TraceSample[]): string {
  const signals = traceSignals(circuit);
  const ids = new Map<string, string>();
  signals.forEach((signal, index) => {
    ids.set(`${signal.group}:${signal.name}`, vcdIdentifier(index));
  });

  const lines: string[] = [];
  lines.push("$date", "  generated by Short Circuit", "$end");
  lines.push("$scope module top $end");
  for (const signal of signals) {
    const id = ids.get(`${signal.group}:${signal.name}`)!;
    const range = signal.width > 1 ? ` [${signal.width - 1}:0]` : "";
    lines.push(`$var wire ${signal.width} ${id} ${signal.name}${range} $end`);
  }
  lines.push("$upscope $end");
  lines.push("$enddefinitions $end");

  const previous = new Map<string, string>();
  trace.forEach((sample, index) => {
    const changes: string[] = [];
    for (const signal of signals) {
      const value = valueFor(sample, signal.group, signal.name);
      const key = `${signal.group}:${signal.name}`;
      if (previous.get(key) === value) continue;
      previous.set(key, value);
      const id = ids.get(key)!;
      if (signal.width === 1) {
        changes.push(`${value}${id}`);
      } else {
        changes.push(`b${value} ${id}`);
      }
    }
    if (changes.length === 0 && sample.events.length === 0) return;
    lines.push(`#${index}`);
    lines.push(...changes);
  });

  return `${lines.join("\n")}\n`;
}

/** Writes the trace as plain JSON, one object per sample. */
export function traceToJson(trace: TraceSample[]): string {
  return JSON.stringify(
    {
      schema: "shortcircuit.trace/v1",
      samples: trace.map((sample, index) => ({
        index,
        label: sample.label,
        inputs: sample.inputs,
        outputs: sample.outputs,
        states: sample.states,
        events: sample.events,
      })),
    },
    null,
    2,
  );
}
