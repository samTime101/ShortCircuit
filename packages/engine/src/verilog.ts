import type { CircuitIR, CircuitNode, ProgramIR } from "./types";

/**
 * Verilog export.
 *
 * The IR is the contract, so the export is a backend: it reads the same graph
 * the simulator runs and writes synthesizable Verilog. Every circuit becomes a
 * module, combinational nodes become continuous assignments, and clocked state
 * becomes an edge-triggered always block with non-blocking assignments, so the
 * atomic commit of the simulator is preserved.
 */

export interface VerilogOptions {
  /** Emit a testbench module for every TEST suite. */
  includeTestbenches?: boolean;
  /** Prefix for every generated module name. */
  modulePrefix?: string;
}

export interface VerilogResult {
  verilog: string;
  warnings: string[];
}

const CATEGORY_ORDER: CircuitNode["kind"][] = ["input", "state", "constant", "operation"];

function sanitize(name: string): string {
  const cleaned = name.replace(/[^A-Za-z0-9_]/g, "_");
  return /^[A-Za-z_]/.test(cleaned) ? cleaned : `n_${cleaned}`;
}

function literal(value: string, width: number): string {
  const bits = value.padStart(width, "0");
  if (width === 1) return `1'b${bits}`;
  return `${width}'b${bits}`;
}

export function exportVerilog(ir: ProgramIR, options: VerilogOptions = {}): VerilogResult {
  const prefix = options.modulePrefix ?? "";
  const warnings: string[] = [];
  const parts: string[] = [
    "// Generated by Short Circuit from shortcircuit.ir/v1.",
    "// Each module is a flattened copy of the compiled graph.",
    "",
  ];

  for (const circuit of ir.circuits) {
    parts.push(moduleFor(circuit, prefix, warnings));
  }

  if (options.includeTestbenches) {
    for (const suite of ir.tests) {
      const circuit = ir.circuits.find((entry) => entry.name === suite.circuit);
      if (!circuit) continue;
      parts.push(testbenchFor(circuit, suite, prefix, warnings));
    }
  }

  return { verilog: `${parts.join("\n").replace(/\n{3,}/g, "\n\n")}\n`, warnings };
}

interface ModuleContext {
  circuit: CircuitIR;
  wires: Map<string, string>;
  states: Map<string, string>;
  constants: Map<string, string>;
  nodes: Map<string, CircuitNode>;
  outputs: Map<string, string>;
  /** Port name for every input, and the port each output is driven by. */
  ports: Map<string, string>;
  warnings: string[];
}

function buildContext(circuit: CircuitIR, warnings: string[]): ModuleContext {
  const nodes = new Map(circuit.nodes.map((node) => [node.id, node]));
  const wires = new Map<string, string>();
  const states = new Map<string, string>();
  const constants = new Map<string, string>();
  const outputs = new Map<string, string>();
  const ports = new Map<string, string>();
  const used = new Set<string>();

  const reserve = (base: string): string => {
    let name = base;
    let counter = 2;
    while (used.has(name)) {
      name = `${base}_${counter}`;
      counter += 1;
    }
    used.add(name);
    return name;
  };

  // Ports are reserved first, so an internal wire never takes a port name.
  for (const input of circuit.inputs) {
    const name = reserve(sanitize(input.name));
    ports.set(input.name, name);
  }
  for (const output of circuit.outputs) {
    const name = reserve(sanitize(output.name));
    outputs.set(output.node, name);
  }

  for (const node of circuit.nodes) {
    if (node.kind === "input") {
      const port = node.inputName ? ports.get(node.inputName) : undefined;
      if (port) wires.set(node.id, port);
      continue;
    }
    if (node.kind === "state") {
      const base = sanitize(
        node.scope.length ? `${node.scope.join("_")}_${node.label}` : node.label,
      );
      // A state that also drives an output keeps a distinct register name.
      const name = used.has(base) ? reserve(`${base}_reg`) : reserve(base);
      states.set(node.id, name);
      wires.set(node.id, name);
      continue;
    }
    if (node.kind === "constant") {
      constants.set(node.id, node.value ?? "0");
      continue;
    }
    // An operation that drives an output is assigned straight to the port.
    const port = outputs.get(node.id);
    const base = node.scope.length ? `${node.scope.join("_")}_${node.label}` : node.label;
    wires.set(node.id, port ?? reserve(sanitize(base)));
  }

  return { circuit, wires, states, constants, nodes, outputs, ports, warnings };
}

function moduleFor(circuit: CircuitIR, prefix: string, warnings: string[]): string {
  const context = buildContext(circuit, warnings);
  const lines: string[] = [];

  const portLines: string[] = [];
  for (const input of circuit.inputs) {
    portLines.push(`  input  ${portWidth(input.width)}${context.ports.get(input.name)}`);
  }
  for (const output of circuit.outputs) {
    portLines.push(`  output ${portWidth(output.width)}${context.outputs.get(output.node) ?? sanitize(output.name)}`);
  }

  lines.push(`module ${prefix}${sanitize(circuit.name)} (`);
  lines.push(portLines.join(",\n"));
  lines.push(");");
  lines.push("");

  // Internal wires for every operation that is not a port.
  for (const node of circuit.nodes) {
    if (node.kind !== "operation") continue;
    if (context.outputs.has(node.id)) continue;
    lines.push(`  wire ${portWidth(node.width)}${context.wires.get(node.id)};`);
  }
  for (const state of circuit.states) {
    const name = context.states.get(state.node);
    if (name) lines.push(`  reg  ${portWidth(state.width)}${name};`);
  }
  if (circuit.nodes.some((node) => node.kind === "operation") || circuit.states.length > 0) {
    lines.push("");
  }

  // Constants.
  for (const node of circuit.nodes) {
    if (node.kind !== "constant") continue;
    const value = node.value ?? "0";
    lines.push(`  localparam ${portWidth(node.width)} ${context.wires.get(node.id) ?? "unused"} = ${literal(value, node.width)};`);
  }
  if (circuit.nodes.some((node) => node.kind === "constant")) lines.push("");

  // Combinational logic.
  for (const node of circuit.nodes) {
    if (node.kind !== "operation") continue;
    const expression = expressionFor(node, context);
    lines.push(`  assign ${context.wires.get(node.id)} = ${expression};`);
  }

  // Outputs that are driven straight from an input, a state, or a constant.
  for (const output of circuit.outputs) {
    if (context.outputs.has(output.node)) continue;
    const source = context.wires.get(output.node);
    const port = context.outputs.get(output.node) ?? sanitize(output.name);
    if (!source) continue;
    lines.push(`  assign ${port} = ${source};`);
  }

  // Clocked state.
  for (const event of circuit.events) {
    const clockNode = context.nodes.get(event.clock);
    const clockWire = clockNode ? context.wires.get(clockNode.id) : undefined;
    if (!clockWire) continue;
    const edge = event.edge === "rising" ? "posedge" : "negedge";
    lines.push("");
    lines.push(`  always @(${edge} ${clockWire}) begin`);
    for (const update of event.updates) {
      const stateName = context.states.get(update.state);
      const valueNode = context.nodes.get(update.value);
      if (!stateName || !valueNode) continue;
      const expression = expressionFor(valueNode, context);
      lines.push(`    ${stateName} <= ${expression};`);
    }
    lines.push("  end");
  }

  // Initial values.
  for (const state of circuit.states) {
    const name = context.states.get(state.node);
    if (!name) continue;
    lines.push("");
    lines.push("  initial begin");
    lines.push(`    ${name} = ${literal(state.init, state.width)};`);
    lines.push("  end");
  }

  lines.push("endmodule");
  lines.push("");
  return lines.join("\n");
}

function portWidth(width: number): string {
  return width > 1 ? `[${width - 1}:0] ` : "";
}

function expressionFor(node: CircuitNode, context: ModuleContext): string {
  if (node.kind === "constant") return literal(node.value ?? "0", node.width);
  if (node.kind === "input" || node.kind === "state") {
    return context.wires.get(node.id) ?? "1'b0";
  }
  const operands = node.operands.map((id) => operandExpression(id, context));
  const op = node.op ?? "";

  switch (op) {
    case "AND":
    case "OR":
    case "XOR":
    case "NAND":
    case "NOR":
    case "XNOR":
      return operands.join(op === "AND" ? " & " : op === "OR" ? " | " : op === "XOR" ? " ^ " : op === "NAND" ? " & " : op === "NOR" ? " | " : " ^ ");
    case "NOT":
      return `~${operands[0] ?? "1'b0"}`;
    case "BUFFER":
      return operands[0] ?? "1'b0";
    case "ADD":
      return `(${operands[0] ?? "0"} + ${operands[1] ?? "0"})`;
    case "SUBTRACT":
      return `(${operands[0] ?? "0"} - ${operands[1] ?? "0"})`;
    case "MULTIPLY":
      return `(${operands[0] ?? "0"} * ${operands[1] ?? "0"})`;
    case "DIVIDE": {
      const divisor = operands[1] ?? "0";
      context.warnings.push(
        `DIVIDE in ${node.label} has no direct hardware meaning when the divisor is zero; the export guards it with zero.`,
      );
      return `((${divisor} != 0) ? (${operands[0] ?? "0"} / ${divisor}) : 0)`;
    }
    case "EQUAL":
      return `(${operands[0] ?? "0"} == ${operands[1] ?? "0"})`;
    case "LESS":
      return `(${operands[0] ?? "0"} < ${operands[1] ?? "0"})`;
    case "GREATER":
      return `(${operands[0] ?? "0"} > ${operands[1] ?? "0"})`;
    case "COMPARE":
      return `((${operands[0] ?? "0"} == ${operands[1] ?? "0"}) ? 2'b00 : ((${operands[0] ?? "0"} < ${operands[1] ?? "0"}) ? 2'b01 : 2'b10))`;
    case "MUX": {
      const select = operands[2] ?? "1'b0";
      return `(${select} ? ${operands[1] ?? "0"} : ${operands[0] ?? "0"})`;
    }
    case "CONCAT":
      return `{${operands.join(", ")}}`;
    case "SLICE": {
      const hi = Number(node.params?.hi ?? 0);
      const lo = Number(node.params?.lo ?? 0);
      return `${operands[0] ?? "0"}[${hi}:${lo}]`;
    }
    case "SHIFT_LEFT":
      return `(${operands[0] ?? "0"} << ${operands[1] ?? "0"})`;
    case "SHIFT_RIGHT":
      return `(${operands[0] ?? "0"} >> ${operands[1] ?? "0"})`;
    case "DECODER": {
      const width = node.width;
      const shift = `{{${Math.max(0, width - 1)}{1'b0}}, 1'b1}`;
      return `(${shift} << ${operands[0] ?? "0"})`;
    }
    case "ENCODER": {
      const source = operands[0] ?? "0";
      const sourceWidth = Number(node.params?.sourceWidth ?? node.width);
      let expression = "0";
      for (let bit = sourceWidth - 1; bit >= 0; bit -= 1) {
        expression = `(${source}[${bit}] ? ${bit} : ${expression})`;
      }
      return expression;
    }
    case "ZEXT": {
      const sourceWidth = Number(node.params?.sourceWidth ?? node.width);
      return `{{${Math.max(0, node.width - sourceWidth)}{1'b0}}, ${operands[0] ?? "0"}}`;
    }
    case "SEXT": {
      const sourceWidth = Number(node.params?.sourceWidth ?? node.width);
      return `{{${Math.max(0, node.width - sourceWidth)}{${operands[0] ?? "0"}[${Math.max(0, sourceWidth - 1)}]}}, ${operands[0] ?? "0"}}`;
    }
    case "POPCOUNT": {
      const sourceWidth = Number(node.params?.sourceWidth ?? node.width);
      const source = operands[0] ?? "0";
      const bits = Array.from({ length: sourceWidth }, (_, index) => `${source}[${index}]`);
      return bits.length > 0 ? `(${bits.join(" + ")})` : "0";
    }
    case "REDUCE_AND":
      return `&${operands[0] ?? "1'b0"}`;
    case "REDUCE_OR":
      return `|${operands[0] ?? "1'b0"}`;
    case "REDUCE_XOR":
      return `^${operands[0] ?? "1'b0"}`;
    case "REPEAT": {
      const count = Number(node.params?.count ?? 1);
      return `{${count}{${operands[0] ?? "1'b0"}}}`;
    }
    case "REVERSE": {
      const sourceWidth = Number(node.params?.sourceWidth ?? node.width);
      const source = operands[0] ?? "0";
      const bits = Array.from({ length: sourceWidth }, (_, index) => `${source}[${index}]`);
      return `{${bits.join(", ")}}`;
    }
    default:
      return "1'b0";
  }
}

function operandExpression(id: string, context: ModuleContext): string {
  const node = context.nodes.get(id);
  if (!node) return "1'b0";
  if (node.kind === "constant") {
    return literal(node.value ?? "0", node.width);
  }
  return context.wires.get(id) ?? context.outputs.get(id) ?? "1'b0";
}

function testbenchFor(
  circuit: CircuitIR,
  suite: ProgramIR["tests"][number],
  prefix: string,
  warnings: string[],
): string {
  const context = buildContext(circuit, warnings);
  const lines: string[] = [];
  lines.push(`module ${prefix}${sanitize(suite.name)}_tb;`);
  for (const input of circuit.inputs) {
    lines.push(`  reg  ${portWidth(input.width)}${context.ports.get(input.name)};`);
  }
  for (const output of circuit.outputs) {
    lines.push(`  wire ${portWidth(output.width)}${context.outputs.get(output.node) ?? sanitize(output.name)};`);
  }
  lines.push("");
  lines.push(`  ${prefix}${sanitize(circuit.name)} dut (`);
  const connections = [
    ...circuit.inputs.map(
      (input) => `.${context.ports.get(input.name)}(${context.ports.get(input.name)})`,
    ),
    ...circuit.outputs.map((output) => `.${sanitize(output.name)}(${sanitize(output.name)})`),
  ];
  lines.push(`    ${connections.join(",\n    ")}`);
  lines.push("  );");
  lines.push("");
  lines.push("  initial begin");
  for (const testCase of suite.cases) {
    lines.push(`    // ${testCase.label}`);
    for (const instruction of testCase.program) {
      if (instruction.kind === "input") {
        const wire = context.ports.get(instruction.name);
        if (wire) lines.push(`    ${wire} = ${literal(instruction.value, instruction.width)};`);
        continue;
      }
      if (instruction.kind === "load") {
        const name = context.states.get(instruction.name);
        if (name) lines.push(`    ${name} = ${literal(instruction.value, instruction.width)};`);
        continue;
      }
      if (instruction.kind === "step") {
        for (const inner of instruction.statements) {
          if (inner.kind !== "input") continue;
          const wire = context.ports.get(inner.name);
          if (wire) lines.push(`    ${wire} = ${literal(inner.value, inner.width)};`);
        }
        lines.push("    #1;");
        continue;
      }
      if (instruction.kind === "cycle") {
        const wire = context.ports.get(instruction.clock);
        for (let index = 0; index < instruction.count; index += 1) {
          if (wire) lines.push(`    ${wire} = 1'b1;`);
          lines.push("    #1;");
          if (wire) lines.push(`    ${wire} = 1'b0;`);
          lines.push("    #1;");
        }
        continue;
      }
      if (instruction.kind === "expect") {
        const signal = context.outputs.get(instruction.actualName) ?? instruction.actualName;
        lines.push(
          `    if (${signal} !== ${literal(instruction.value, instruction.width)}) $display("FAIL %s: expected %b, got %b", "${testCase.label}: ${instruction.actualName}", ${literal(instruction.value, instruction.width)}, ${signal});`,
        );
      }
    }
  }
  lines.push("    $finish;");
  lines.push("  end");
  lines.push("endmodule");
  lines.push("");
  return lines.join("\n");
}
